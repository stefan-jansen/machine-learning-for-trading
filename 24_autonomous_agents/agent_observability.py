TRACES_DIR = Path(__file__).resolve().parent / "forecast_traces"

# A process-wide monotonic counter so calls captured by *different* tracers
# (e.g. one per agent thread in NB06) can still be merged back into the true
# chronological order. ``itertools.count`` is not atomic across threads, so we
# guard it with a lock.
_SEQ = itertools.count()
_SEQ_LOCK = threading.Lock()


def _next_seq() -> int:
    with _SEQ_LOCK:
        return next(_SEQ)


def _now_iso() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


# ---------------------------------------------------------------------------
# Serialization helper
# ---------------------------------------------------------------------------


def to_serializable(obj: Any) -> Any:
    """Recursively convert dataclasses, enums, and containers to JSON-safe types."""
    if dataclasses.is_dataclass(obj) and not isinstance(obj, type):
        return to_serializable(dataclasses.asdict(obj))
    if isinstance(obj, Enum):
        return obj.value
    if isinstance(obj, dict):
        return {str(k): to_serializable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [to_serializable(v) for v in obj]
    return obj


