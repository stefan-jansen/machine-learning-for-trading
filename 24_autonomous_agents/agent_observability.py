"""Agent observability: full-trace capture, persistence, and replay.

Autonomous agents are only trustworthy if you can see what they did. This
module gives the forecasting notebooks a single, auditable record of every
run: the question, every prompt an agent received, every raw model response,
every search query and the documents it returned, and the structured forecast
that came out the other end.

Three pieces, each independent:

1. ``TracingLLMClient`` wraps *any* ``LLMClient`` and records every call —
   the exact messages sent in and the raw text returned — without changing a
   line of agent logic. Because every agent in the chapter (research, debate,
   supervisor) talks to the model through the same ``complete_with_usage``
   interface, wrapping the client captures the whole conversation for free.

2. ``RunTrace`` bundles the question, the structured artifacts, and the raw
   model I/O into one object that serializes to JSON (``save``) and reloads
   (``load``). That file is the durable, replayable record of a point-in-time
   run — the thing you hand to a reviewer who asks "show me exactly what the
   agents saw and said."

3. The ``show_*`` renderers turn an in-memory artifact (or a reloaded trace)
   into a clean, untruncated, chronological readout so a reader can follow how
   each agent proceeds over time.

The captured JSON lives in ``forecast_traces/`` (git-ignored, regenerated by
re-running a notebook), mirroring the ``operator_artifacts/`` convention.
"""

from __future__ import annotations

