@dataclass(slots=True)
class LLMCall:
    """One model invocation: everything sent in, everything returned."""

    seq: int
    label: str
    model: str
    json_mode: bool
    messages: list[dict[str, str]]  # the full prompt: [{"role", "content"}, ...]
    response: str  # raw model output, untruncated
    input_tokens: int
    output_tokens: int
    total_tokens: int
    timestamp: str


class TracingLLMClient:
    """Wraps any ``LLMClient`` and records every call.

    Drop-in replacement for the wrapped client — it satisfies the same
    ``LLMClient`` protocol (``model_name``, ``complete``,
    ``complete_with_usage``) and forwards to the inner client, appending an
    ``LLMCall`` record on every completion.

    Thread-safe: ``list.append`` is atomic under CPython's GIL and the
    sequence counter is locked, so a single tracer can be shared across
    threads. In practice (e.g. NB06's ``ThreadPoolExecutor``) it is cleaner to
    give each agent its own tracer with a distinct ``label`` and
    :func:`merge_calls` them afterwards, so each call is attributed to the
    agent that made it.
    """

    def __init__(self, inner: LLMClient, label: str = "") -> None:
        self._inner = inner
        self.label = label
        self.calls: list[LLMCall] = []

    @property
    def model_name(self) -> str:
        return self._inner.model_name

    def complete(self, messages: list[ChatMessage], json_mode: bool = False) -> str:
        text, _ = self.complete_with_usage(messages, json_mode)
        return text

    def complete_with_usage(self, messages: list[ChatMessage], json_mode: bool = False):
        text, usage = self._inner.complete_with_usage(messages, json_mode)
        self.calls.append(
            LLMCall(
                seq=_next_seq(),
                label=self.label,
                model=self._inner.model_name,
                json_mode=json_mode,
                messages=[{"role": m.role, "content": m.content} for m in messages],
                response=text,
                input_tokens=usage.input_tokens,
                output_tokens=usage.output_tokens,
                total_tokens=usage.total_tokens,
                timestamp=_now_iso(),
            )
        )
        return text, usage


def trace_llm(inner: LLMClient, label: str = "") -> TracingLLMClient:
    """Convenience constructor: ``llm = trace_llm(create_llm_client(...))``."""
    return TracingLLMClient(inner, label=label)


def merge_calls(*sources: TracingLLMClient | list[LLMCall]) -> list[LLMCall]:
    """Combine call logs from several tracers into one chronological list."""
    calls: list[LLMCall] = []
    for src in sources:
        calls.extend(src.calls if isinstance(src, TracingLLMClient) else src)
    return sorted(calls, key=lambda c: c.seq)


